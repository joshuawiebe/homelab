#!/usr/bin/env bash
set -euo pipefail

# Source shared logging module
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$(dirname "$SCRIPT_DIR")/../.shared/log.sh" 2>/dev/null || {
  echo "[ERROR] Failed to load logging module"
  exit 1
}

ENV_FILE="$SCRIPT_DIR/.env"

section "HomeLab Auto Backup Setup"

# --- Configuration input ---
subsection "Backup Configuration"

info "Enter USB and backup details:"
echo ""
read -rp "  USB device path (e.g., /dev/sda1): " USB_DEVICE
read -rp "  USB mount point (e.g., /mnt/backup_usb): " BACKUP_MOUNT
read -rp "  Source path to backup (e.g., /mnt/ssd/): " BACKUP_SRC

read -rp "  Borg repo path [/mnt/backup_usb/borgrepo]: " BORG_REPO
BORG_REPO=${BORG_REPO:-/mnt/backup_usb/borgrepo}

read -rp "  Daily backup time [02:00:00]: " BACKUP_TIME
BACKUP_TIME=${BACKUP_TIME:-02:00:00}

read -rp "  Systemd service name [auto-backup]: " SERVICE_NAME
SERVICE_NAME=${SERVICE_NAME:-auto-backup}

read -rp "  Default proxy [traefik]: " DEFAULT_PROXY
DEFAULT_PROXY=${DEFAULT_PROXY:-traefik}

echo ""
info "Enter Borg backup passphrase (will not be echoed):"
read -s -rp "  Passphrase: " BORG_PASSPHRASE
echo ""
read -s -rp "  Confirm: " BORG_PASSPHRASE_CONFIRM
echo ""

if [ "$BORG_PASSPHRASE" != "$BORG_PASSPHRASE_CONFIRM" ]; then
  error "Passphrases do not match"
  exit 1
fi

success "Configuration validated"
echo ""

# --- Save configuration ---
subsection "Saving Configuration"

cat > "$ENV_FILE" <<EOF
# auto_backup/.env (generated by setup)
# Do not commit this file - contains sensitive data!

USB_DEVICE=$USB_DEVICE
BACKUP_USB_LABEL=BACKUP_USB
BACKUP_MOUNT=$BACKUP_MOUNT
BACKUP_SRC=$BACKUP_SRC
BORG_REPO=$BORG_REPO
BORG_PASSPHRASE=$BORG_PASSPHRASE
LOG_FILE=$SCRIPT_DIR/backup.log
BACKUP_TIME=$BACKUP_TIME
SERVICE_NAME=$SERVICE_NAME
DEFAULT_PROXY=$DEFAULT_PROXY
EOF

success "Configuration saved: $ENV_FILE"
echo ""

# --- Create systemd service ---
subsection "Creating Systemd Service"

SERVICE_FILE="/etc/systemd/system/$SERVICE_NAME.service"
TIMER_FILE="/etc/systemd/system/$SERVICE_NAME.timer"

info "Creating service file: $SERVICE_FILE"
sudo tee "$SERVICE_FILE" > /dev/null <<EOF
[Unit]
Description=Automatic Borg Backup
After=network.target

[Service]
Type=oneshot
EnvironmentFile=$ENV_FILE
ExecStart=$SCRIPT_DIR/backup_start.sh
StandardOutput=journal
StandardError=journal
EOF

success "Service file created"

info "Creating timer file: $TIMER_FILE"
sudo tee "$TIMER_FILE" > /dev/null <<EOF
[Unit]
Description=Run automatic backup daily at $BACKUP_TIME
Requires=$SERVICE_NAME.service

[Timer]
OnCalendar=*-*-* $BACKUP_TIME
Persistent=true
AccuracySec=1m

[Install]
WantedBy=timers.target
EOF

success "Timer file created"
echo ""

# --- Enable and start timer ---
subsection "Starting Backup Service"

info "Reloading systemd daemon..."
sudo systemctl daemon-reload
success "Daemon reloaded"

info "Enabling $SERVICE_NAME.timer..."
sudo systemctl enable "$SERVICE_NAME.timer"
success "Timer enabled"

info "Starting $SERVICE_NAME.timer..."
sudo systemctl start "$SERVICE_NAME.timer"
success "Timer started"
echo ""

# --- Verification ---
subsection "Verification"

info "Service status:"
sudo systemctl status "$SERVICE_NAME.timer" --no-pager
echo ""

# --- Summary ---
separator
echo ""
success "Auto Backup Setup Complete!"
echo ""
info "Configuration Details:"
info "  Config file: $ENV_FILE"
info "  Service: $SERVICE_NAME"
info "  Schedule: Daily at $BACKUP_TIME"
info "  Backup source: $BACKUP_SRC"
info "  Borg repo: $BORG_REPO"
echo ""
info "Useful commands:"
info "  Check status: sudo systemctl status $SERVICE_NAME.timer"
info "  View logs: journalctl -u $SERVICE_NAME.service -f"
info "  Run manually: sudo systemctl start $SERVICE_NAME.service"
info "  Remove setup: $SCRIPT_DIR/backup_remove.sh"
echo ""
exit_success "Setup complete!"

